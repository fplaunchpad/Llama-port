#!/usr/bin/env python3
"""
Region profiler: where do the cycles go in each port, and where do the OCaml builds
lose to C++ - and to each other.

    wsl -d Debian -- python3 tools/profile_regions.py                    # gen, all ports
    wsl -d Debian -- python3 tools/profile_regions.py --mode ppl
    wsl -d Debian -- python3 tools/profile_regions.py --impls cpp
    wsl -d Debian -- python3 tools/profile_regions.py --impls ocaml,oxcaml

Must run inside one Linux environment, for the same reason tools/bench_wsl.sh does:
comparing a WSL binary against a Windows-native one measures the OS and libm.

WHY NOT perf
------------
`perf` needs root to install here, WSL2 exposes no virtualized PMU (so only the
cpu-clock software event works), and flambda2 -O3 inlines the entire forward pass
into one symbol - so symbol-level attribution would report "it is all in
camlMain__forward" and tell us nothing about which chunk is slow. Region counters
read the same TSC in both languages and split the forward pass the same way, which
is the only form of this measurement that is comparable across the two backends.

METHOD
------
The shipped sources are never modified. Instrumented copies are generated by
anchored statement insertion: each edit below quotes real lines from the port and
re-emits them with prof_start/prof_stop around them. Every anchor must match
exactly once, so if either port is edited such that an anchor moves, this tool
fails loudly rather than silently profiling stale code. The regions are the same
seven PORTING.md section 7 used, so the numbers here line up with the Rust column
already published there.

CAVEATS, both real
------------------
1. Observer effect. Two rdtsc reads per region cost roughly 30-60 cycles, and the
   region boundaries act as scheduling barriers that inhibit some cross-region
   optimization. The tool measures the empty-region cost in each binary and
   subtracts it, and reports instrumented vs shipped tok/s so the distortion is
   visible instead of assumed. Small regions (embed) carry the most error.
2. rdtsc counts invariant-TSC reference ticks, not core clocks. Shares and ratios
   are unaffected; absolute cycles/op is off by the turbo ratio.
"""

